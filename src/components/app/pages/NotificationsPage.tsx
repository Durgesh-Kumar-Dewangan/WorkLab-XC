'use client';

import { useState } from 'react';
import Link from 'next/link';
import { Icon } from '@/components/ui/Icon';
import { Segmented } from '@/components/ui/controls';
import { useApp } from '@/lib/store';
import { toast } from '@/lib/ui/toast';
import { ago } from '@/lib/util';

type Filter = 'all' | 'unread' | 'revision' | 'progress' | 'system';
const KINDS: Record<string, string> = {
  revision: 'Revision',
  progress: 'Progress',
  system: 'System',
  tip: 'Tip',
  tips: 'Tip',
};

export function NotificationsPage() {
  const [filter, setFilter] = useState<Filter>('all');
  const all = useApp((s) => s.notifications);
  const markRead = useApp((s) => s.markRead);
  const remove = useApp((s) => s.removeNotification);
  const toggle = useApp((s) => s.toggleRead);
  const items = all.filter((n) => filter === 'all' || (filter === 'unread' ? !n.read : n.kind === filter));

  return (
    <div className="page">
      <div className="ph">
        <div>
          <h1>Notifications</h1>
          <p className="sub">
            Revision reminders and progress notes generated by simple rules on your own answers. Choose which
            kinds you want in Settings.
          </p>
        </div>
        <div className="acts">
          <button
            className="btn"
            type="button"
            onClick={() => {
              markRead();
              toast('All marked as read', 'ok');
            }}
          >
            Mark all read
          </button>
          <Link href="/app/settings" className="btn ghost">
            Preferences
          </Link>
        </div>
      </div>
      <Segmented<Filter>
        ariaLabel="Filter notifications"
        value={filter}
        onChange={setFilter}
        options={[
          { value: 'all', label: 'All' },
          { value: 'unread', label: 'Unread' },
          { value: 'revision', label: 'Revision' },
          { value: 'progress', label: 'Progress' },
          { value: 'system', label: 'System' },
        ]}
      />
      <div className="card">
        {items.length ? (
          <div className="list">
            {items.map((n) => (
              <div className="li" key={n.id}>
                <div className="ico">
                  <Icon
                    name={
                      n.kind === 'revision'
                        ? 'refresh'
                        : n.kind === 'progress'
                          ? 'award'
                          : n.kind === 'tip' || n.kind === 'tips'
                            ? 'sparkles'
                            : 'info'
                    }
                    size={16}
                  />
                </div>
                <div className="grow">
                  <div className="row">
                    <span className="t" style={{ fontWeight: n.read ? 400 : 600 }}>
                      {n.title}
                    </span>
                    {n.read ? null : <span className="dotbadge" title="Unread" />}
                  </div>
                  <div className="s" style={{ whiteSpace: 'normal' }}>
                    {n.body}
                  </div>
                  <div className="s">
                    {KINDS[n.kind] ?? 'Note'} · {ago(n.ts)}
                  </div>
                </div>
                {n.link ? (
                  <Link href={n.link} className="btn xs" onClick={() => markRead(n.id)}>
                    Open
                  </Link>
                ) : null}
                <button
                  className="icon-btn sm"
                  type="button"
                  aria-label={n.read ? 'Mark as unread' : 'Mark as read'}
                  title={n.read ? 'Mark as unread' : 'Mark as read'}
                  onClick={() => toggle(n.id)}
                >
                  <Icon name="check" size={15} />
                </button>
                <button
                  className="icon-btn sm"
                  type="button"
                  aria-label="Dismiss notification"
                  onClick={() => remove(n.id)}
                >
                  <Icon name="x" size={15} />
                </button>
              </div>
            ))}
          </div>
        ) : (
          <div className="empty" style={{ border: 0 }}>
            <Icon name="bell" size={24} />
            <p className="body">{filter === 'all' ? 'You are all caught up.' : 'Nothing in this filter.'}</p>
          </div>
        )}
      </div>
    </div>
  );
}
