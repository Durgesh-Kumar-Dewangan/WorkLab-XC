import type { ConfQuestion, McqQuestion, NumQuestion, Slide, Topic, Unit } from '../domain/types';

const mcq = (q: string, opts: string[], ans: number, why: string): McqQuestion => ({
  type: 'mcq',
  q,
  opts,
  ans,
  why,
});
const num = (
  q: string,
  ans: number,
  tol: number | undefined,
  unit: string | undefined,
  why: string,
): NumQuestion => ({
  type: 'num',
  q,
  ans,
  tol: tol === undefined ? 0.01 : tol,
  unit: unit || '',
  why,
});
export const conf = (q: string, why: string): ConfQuestion => ({ type: 'conf', q, why });
const sl = (t: string, b: string[], say: string, o?: Partial<Slide>): Slide => ({
  t,
  b,
  say,
  av: 'talk',
  cam: 'board',
  ...o,
});

